"""Paper (RA-L) figure/table pipeline -- pure post-processing, no Isaac Sim, no GPU.

Reads already-computed summary.json / eval outputs from the experiments tree and
renders single-column RA-L-style PDF+PNG figures plus CSV/LaTeX tables. Reuses the
existing sim-free engine (`_analyze.recompute_metrics.floor_verdict`/`unit_for`,
DR_LEVELS/DR_SCALE) for all metric math -- this script only assembles + renders,
it recomputes nothing eval.py or compare.py already computes correctly (avoids the
three-drifted-implementations trap documented in recompute_metrics.py).

Run from the repo root with plain python3 (matplotlib/numpy only):
    python3 tools/paper_figures.py all
    python3 tools/paper_figures.py fault-ablation
    python3 tools/paper_figures.py teacher-summary
    python3 tools/paper_figures.py doraemon-curriculum
    python3 tools/paper_figures.py student-comparison

Each figure's output directory is the SSOT run's own `analysis/paper_figures/`
(never a new top-level location) and gets a manifest.json recording source
summary.json paths (+ sha256), the figures/tables produced, and any caveats
(e.g. single-seed screening) -- so a reader can trace every number back to disk.
"""

