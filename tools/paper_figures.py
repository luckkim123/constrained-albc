DR_LEVEL_COLORS = {"none": "#4C72B0", "soft": "#55A868", "medium": "#DD8452", "hard": "#C44E52"}
ARM_COLORS = ["#4C72B0", "#DD8452", "#55A868", "#8172B2"]


def _sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def _git_sha() -> str:
    try:
        return subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=REPO_ROOT, capture_output=True, text=True, timeout=5
        ).stdout.strip() or "unknown"
    except Exception:
        return "unknown"


def _load_summary(path: str) -> dict:
    if not os.path.isfile(path):
        raise FileNotFoundError(f"summary.json not found: {path}")
    with open(path) as f:
        return json.load(f)


def _val(summary: dict, lvl: str, axis: str, field: str):
    return summary.get(lvl, {}).get(axis, {}).get(field)


def _write_manifest(out_dir: str, source_files: list[str], outputs: list[str], caveats: list[str], extra: dict | None = None) -> str:
    manifest = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "generator": "tools/paper_figures.py",
        "argv": sys.argv,
        "git_sha": _git_sha(),
        "source_files": [{"path": p, "sha256": _sha256(p)} for p in source_files],
        "outputs": outputs,
        "caveats": caveats,
    }
    if extra:
        manifest.update(extra)
    path = os.path.join(out_dir, "manifest.json")
    with open(path, "w") as f:
        json.dump(manifest, f, indent=2)
    return path


def _write_csv(path: str, header: list[str], rows: list[list]) -> None:
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)


def _write_latex_table(path: str, caption: str, label: str, header: list[str], rows: list[list], col_align: str | None = None) -> None:
    ncols = len(header)
    align = col_align or ("l" + "r" * (ncols - 1))
    lines = [
        r"% auto-generated by tools/paper_figures.py -- do not hand-edit, regenerate instead",
        r"\begin{table}[t]",
        r"\centering",
        rf"\caption{{{caption}}}",
        rf"\label{{{label}}}",
        rf"\begin{{tabular}}{{{align}}}",
        r"\toprule",
        " & ".join(header) + r" \\",
        r"\midrule",
    ]
    for row in rows:
        lines.append(" & ".join(str(c) for c in row) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def _savefig(fig, out_dir: str, stem: str) -> list[str]:
    png = os.path.join(out_dir, f"{stem}.png")
    pdf = os.path.join(out_dir, f"{stem}.pdf")
    fig.savefig(png, bbox_inches="tight")
    fig.savefig(pdf, bbox_inches="tight")
    plt.close(fig)
    return [os.path.basename(png), os.path.basename(pdf)]


