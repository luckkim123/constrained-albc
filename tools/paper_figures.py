def _latest_summary(run_dir: str) -> str | None:
    eval_dir = os.path.join(run_dir, "eval")
    if not os.path.isdir(eval_dir):
        return None
    summaries = [
        cand for sub in sorted(os.listdir(eval_dir))
        if os.path.isfile(cand := os.path.join(eval_dir, sub, "summary.json"))
    ]
    return summaries[-1] if summaries else None


def cmd_student_comparison(_args: argparse.Namespace) -> None:
    arms: list[tuple[str, str]] = []
    missing = []
    for label, run_dir in STUDENT_COMPARISON_CANDIDATES:
        summary_path = _latest_summary(run_dir)
        if summary_path is None:
            missing.append(label)
        else:
            arms.append((label, summary_path))
    if missing:
        print(f"[student-comparison] SKIPPED (T11/E1): no eval summary.json for {missing}. "
              f"Nothing written.")
        return
    arms.append(STUDENT_COMPARISON_ANCHOR)

    out_dir = os.path.join(STUDENT_COMPARISON_RUN_DIR, "analysis", "paper_figures")
    os.makedirs(out_dir, exist_ok=True)

    axis, field = "att_norm", "ss_error"
    source_files = [p for _, p in arms]
    # {arm_label: {level: value}}
    results: dict[str, dict[str, float]] = {}
    survival: dict[str, dict[str, float]] = {}
    for label, path in arms:
        s = _load_summary(path)
        results[label] = {lvl: _val(s, lvl, axis, field) for lvl in DR_LEVELS}
        survival[label] = {lvl: s.get(lvl, {}).get("survival_pct") for lvl in DR_LEVELS}

    with plt.rc_context(RAL_RC):
        fig, ax = plt.subplots(figsize=(3.45, 2.5))
        n_arms = len(arms)
        x = np.arange(len(DR_LEVELS))
        width = 0.8 / n_arms
        for i, (label, _) in enumerate(arms):
            vals = [results[label][lvl] for lvl in DR_LEVELS]
            ax.bar(x + (i - (n_arms - 1) / 2) * width, vals, width, label=label, color=ARM_COLORS[i])
        ax.set_xticks(x)
        ax.set_xticklabels(DR_LEVELS)
        ax.set_ylabel(f"att_norm ss_error [{unit_for(axis, field)}]")
        ax.set_xlabel("DR level")
        ax.legend(loc="upper left", frameon=False, fontsize=6)
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
        ax.text(0.99, 0.02, "n=1 (seed 42)", transform=ax.transAxes,
                 ha="right", va="bottom", fontsize=6, color="0.4", style="italic")
        outputs = _savefig(fig, out_dir, "student_comparison")

    header = ["DR level"] + [label for label, _ in arms] + ["survival % (TCN/GRU/teacher)"]
    rows = []
    for lvl in DR_LEVELS:
        surv_cell = "/".join(f"{survival[label][lvl]:.1f}" for label, _ in arms)
        rows.append([lvl] + [f"{results[label][lvl]:.4f}" for label, _ in arms] + [surv_cell])
    csv_path = os.path.join(out_dir, "student_comparison.csv")
    _write_csv(csv_path, header, rows)
    tex_header = ["DR level"] + [label for label, _ in arms]
    tex_rows = [[lvl] + [f"{results[label][lvl]:.3f}" for label, _ in arms] for lvl in DR_LEVELS]
    tex_path = os.path.join(out_dir, "student_comparison.tex")
    _write_latex_table(
        tex_path,
        caption=(
            "Deployed student encoder comparison: attitude-norm steady-state tracking "
            r"error (degrees, lower is better) for TCN and GRU/C3 partial-observation "
            r"students against the full-state teacher (\texttt{model\_9998}) anchor. "
            "GRU has lower ss\\_error than TCN at every DR level; both students trail "
            "the full-state teacher, as expected from the reduced observation. "
            "Single-seed (seed 42) screening observation, not a statistical test."
        ),
        label="tab:student_comparison",
        header=tex_header,
        rows=tex_rows,
    )
    outputs += [os.path.basename(csv_path), os.path.basename(tex_path)]

    manifest_path = _write_manifest(
        out_dir,
        source_files,
        outputs,
        caveats=[
            "Single seed (42) per arm -- a screening comparison, not a statistical test; "
            "no cross-seed variance is available for TCN vs. GRU.",
            "The teacher arm is a full-state anchor, not a peer baseline: it has no "
            "partial-observation encoder, so its lower error is an upper bound on what "
            "encoding-induced degradation the students pay, not evidence about TCN vs. GRU "
            "encoder quality by itself.",
            "hard-level TCN/GRU both show 1 of 64 envs failing to survive (98.4%) while the "
            "teacher survives 64/64 -- their hard-level ss_error_std is inflated by that "
            "excursion (see source summary.json), so the hard-level point estimate is "
            "noisier than none/soft/medium.",
        ],
        extra={"axis": axis, "field": field, "seed": 42},
    )
    print(f"[student-comparison] wrote {len(outputs)} files to {out_dir}")
    print(f"[student-comparison] manifest: {manifest_path}")


