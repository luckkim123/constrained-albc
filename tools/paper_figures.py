def cmd_fault_ablation(_args: argparse.Namespace) -> None:
    out_dir = os.path.join(FAULT_ABLATION_RUN_DIR, "analysis", "paper_figures")
    os.makedirs(out_dir, exist_ok=True)

    axis, field = "att_norm", "ss_error"
    floor = DECISION_FLOORS[field]
    source_files = []
    # {arm_label: {level: (delta, verdict)}}
    results: dict[str, dict[str, tuple[float, str]]] = {}
    for label, healthy_path, dead_path in FAULT_ABLATION_ARMS:
        source_files += [healthy_path, dead_path]
        healthy, dead = _load_summary(healthy_path), _load_summary(dead_path)
        per_level = {}
        for lvl in DR_LEVELS:
            h, d = _val(healthy, lvl, axis, field), _val(dead, lvl, axis, field)
            if h is None or d is None:
                per_level[lvl] = (float("nan"), "NO-FLOOR")
                continue
            delta = float(d) - float(h)
            per_level[lvl] = (delta, floor_verdict(field, delta, axis))
        results[label] = per_level

    # -- figure: grouped bars, delta att_norm ss_error (deg) per DR level per arm --
    with plt.rc_context(RAL_RC):
        fig, ax = plt.subplots(figsize=(3.45, 2.5))
        n_arms = len(FAULT_ABLATION_ARMS)
        x = np.arange(len(DR_LEVELS))
        width = 0.8 / n_arms
        for i, (label, _, _) in enumerate(FAULT_ABLATION_ARMS):
            deltas = [results[label][lvl][0] for lvl in DR_LEVELS]
            ax.bar(x + (i - (n_arms - 1) / 2) * width, deltas, width, label=label, color=ARM_COLORS[i])
        ax.axhline(floor, color="0.4", linestyle="--", linewidth=0.7, label=f"screening floor ({floor:g}°)")
        ax.set_xticks(x)
        ax.set_xticklabels(DR_LEVELS)
        ax.set_ylabel(f"Δ att_norm ss_error [{unit_for(axis, field)}]\n(m4-dead − healthy)")
        ax.set_xlabel("DR level")
        ax.legend(loc="upper left", frameon=False)
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
        outputs = _savefig(fig, out_dir, "fault_dr_ablation")

    # -- table: CSV + LaTeX --
    header = ["DR level"] + [label for label, _, _ in FAULT_ABLATION_ARMS]
    rows = []
    for lvl in DR_LEVELS:
        row = [lvl]
        for label, _, _ in FAULT_ABLATION_ARMS:
            delta, verdict = results[label][lvl]
            mark = "" if verdict == "REAL" else " (below floor)"
            row.append(f"{delta:+.3f}{mark}")
        rows.append(row)
    csv_path = os.path.join(out_dir, "fault_dr_ablation.csv")
    _write_csv(csv_path, header, rows)
    tex_rows = []
    for lvl in DR_LEVELS:
        row = [lvl]
        for label, _, _ in FAULT_ABLATION_ARMS:
            delta, verdict = results[label][lvl]
            cell = f"{delta:+.3f}"
            if verdict != "REAL":
                cell += r"$^{\dagger}$"
            row.append(cell)
        tex_rows.append(row)
    tex_path = os.path.join(out_dir, "fault_dr_ablation.tex")
    _write_latex_table(
        tex_path,
        caption=(
            r"Fault-tolerance ablation: $\Delta$ attitude-norm steady-state error "
            r"(m4-dead $-$ healthy, degrees) across DR levels. "
            r"$^{\dagger}$below the 0.10\textdegree{} screening floor (noise, single seed)."
        ),
        label="tab:fault_dr_ablation",
        header=header,
        rows=tex_rows,
    )
    outputs += [os.path.basename(csv_path), os.path.basename(tex_path)]

    manifest_path = _write_manifest(
        out_dir,
        source_files,
        outputs,
        caveats=[
            "n=1 (single seed 30) per arm; REAL/BELOW-FLOOR verdicts use the workspace's "
            "pre-registered screening floors (_analyze/recompute_metrics.DECISION_FLOORS), "
            "not a statistical test.",
            "E-ftc1 (severity-head-start run) intentionally excluded -- its own wiki entry "
            "flags it 'never a paper number' (single-seed screening only).",
        ],
        extra={"axis": axis, "field": field, "floor_deg": floor},
    )
    print(f"[fault-ablation] wrote {len(outputs)} files to {out_dir}")
    print(f"[fault-ablation] manifest: {manifest_path}")


